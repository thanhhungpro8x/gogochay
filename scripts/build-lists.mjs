#!/usr/bin/env node
// Downloads each filter list at a PINNED commit and generates the extension's bundled data.
// This is the ONLY step that touches the network. The extension itself never does.
//
//   node scripts/build-lists.mjs            # uses the commits pinned in lists.config.json
//   node scripts/build-lists.mjs --latest   # resolves each list's current HEAD, pins it, rebuilds
//
// Output:
//   extension/rules/<id>.json      one declarativeNetRequest ruleset per list (network blocking)
//   extension/data/cosmetic.js     CSS selectors to hide, all lists merged
//   extension/data/lists-info.json what was built from what (shown in the tray)
//   extension/manifest.json        rule_resources kept in sync with the lists

import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { convertLists, mergeCosmetic } from './convert.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ext = path.join(root, 'extension');
const configPath = path.join(root, 'lists.config.json');
const config = JSON.parse(await readFile(configPath, 'utf8'));
const latest = process.argv.includes('--latest');

if (latest) {
  for (const src of config.sources) {
    const out = execFileSync('git', ['ls-remote', `https://github.com/${src.repo}.git`, 'HEAD']).toString();
    src.commit = out.split(/\s+/)[0];
    console.log(`Pinned ${src.repo}@${src.commit}`);
  }
  await writeFile(configPath, JSON.stringify(config, null, 2) + '\n');
}

await mkdir(path.join(ext, 'rules'), { recursive: true });
await mkdir(path.join(ext, 'data'), { recursive: true });
for (const f of await readdir(path.join(ext, 'rules'))) await unlink(path.join(ext, 'rules', f));

const cosmetics = [];
const info = { generatedAt: new Date().toISOString(), lists: [] };

for (const src of config.sources) {
  const parts = [];
  const files = [];
  for (const file of src.files) {
    const url = `https://raw.githubusercontent.com/${src.repo}/${src.commit}/${file}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
    const text = await res.text();
    parts.push(text);
    files.push({ file, sha256: createHash('sha256').update(text).digest('hex') });
  }
  const { rules, cosmetic, stats } = convertLists(parts.join('\n'));
  await writeFile(path.join(ext, 'rules', `${src.id}.json`), JSON.stringify(rules));
  cosmetics.push(cosmetic);
  info.lists.push({
    id: src.id,
    name: src.name,
    license: src.license,
    source: `https://github.com/${src.repo}`,
    commit: src.commit,
    files,
    stats: { ...stats, genericSelectors: cosmetic.generic.length, sitesWithSpecificSelectors: Object.keys(cosmetic.specific).length },
  });
  console.log(`${src.id}: ${stats.network} network filters → ${stats.dnrRules} rules, ${stats.cosmetic} cosmetic, ${stats.skipped} skipped`);
}

await writeFile(
  path.join(ext, 'data', 'cosmetic.js'),
  '// GENERATED by scripts/build-lists.mjs — do not edit.\n' +
  '// Data from the lists in lists.config.json; licenses in NOTICE.\n' +
  `self.AD_TRAY_COSMETIC = ${JSON.stringify(mergeCosmetic(cosmetics))};\n`,
);
await writeFile(path.join(ext, 'data', 'lists-info.json'), JSON.stringify(info, null, 2) + '\n');

// keep manifest.json's rulesets in sync with the configured lists
const manifestPath = path.join(ext, 'manifest.json');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
manifest.declarative_net_request.rule_resources = config.sources.map((s) => ({ id: s.id, enabled: true, path: `rules/${s.id}.json` }));
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
