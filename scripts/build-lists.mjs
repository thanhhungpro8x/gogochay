#!/usr/bin/env node
// Downloads EasyList at a PINNED commit and generates the extension's bundled data.
// This is the ONLY step that touches the network. The extension itself never does.
//
//   node scripts/build-lists.mjs            # uses the commit pinned in lists.config.json
//   node scripts/build-lists.mjs --latest   # resolves current master, pins it, rebuilds
//   node scripts/build-lists.mjs --local DIR  # use already-downloaded .txt files (offline)

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { convertLists } from './convert.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const configPath = path.join(root, 'lists.config.json');
const config = JSON.parse(await readFile(configPath, 'utf8'));
const args = process.argv.slice(2);

if (args.includes('--latest')) {
  const out = execFileSync('git', ['ls-remote', `https://github.com/${config.repo}.git`, 'refs/heads/master']).toString();
  config.commit = out.split(/\s+/)[0];
  await writeFile(configPath, JSON.stringify(config, null, 2) + '\n');
  console.log(`Pinned ${config.repo}@${config.commit}`);
}

const localDir = args.includes('--local') ? args[args.indexOf('--local') + 1] : null;
const parts = [];
const sources = [];
for (const file of config.files) {
  let text;
  if (localDir) {
    text = await readFile(path.join(localDir, path.basename(file)), 'utf8');
  } else {
    const url = `https://raw.githubusercontent.com/${config.repo}/${config.commit}/${file}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
    text = await res.text();
  }
  parts.push(text);
  sources.push({ file, sha256: createHash('sha256').update(text).digest('hex') });
}

const { rules, cosmetic, stats } = convertLists(parts.join('\n'));

const ext = path.join(root, 'extension');
await mkdir(path.join(ext, 'rules'), { recursive: true });
await mkdir(path.join(ext, 'data'), { recursive: true });
await writeFile(path.join(ext, 'rules', 'easylist.json'), JSON.stringify(rules));
await writeFile(
  path.join(ext, 'data', 'cosmetic.js'),
  '// GENERATED by scripts/build-lists.mjs from EasyList — do not edit.\n' +
  '// License of this data: EasyList (GPLv3 / CC BY-SA 3.0), see NOTICE.\n' +
  `self.AD_TRAY_COSMETIC = ${JSON.stringify(cosmetic)};\n`,
);
const info = {
  source: `https://github.com/${config.repo}`,
  commit: localDir ? `local:${localDir}` : config.commit,
  generatedAt: new Date().toISOString(),
  files: sources,
  stats: { ...stats, genericSelectors: cosmetic.generic.length, sitesWithSpecificSelectors: Object.keys(cosmetic.specific).length },
};
await writeFile(path.join(ext, 'data', 'lists-info.json'), JSON.stringify(info, null, 2) + '\n');
console.log(JSON.stringify(info.stats, null, 2));
